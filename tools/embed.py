#!/usr/bin/env python3
"""Regenerate src/index_html.h (from web/index.html) and src/default_conf.h (from netguard.conf):  python3 tools/embed.py"""
import pathlib
root = pathlib.Path(__file__).resolve().parent.parent

def emit(src, dst, name):
    data = (root / src).read_bytes()
    rows = [", ".join("0x%02x" % b for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    out = ("/* generated by tools/embed.py from %s - do not edit */\n"
           "static const unsigned char %s[] = {\n  " % (src, name) + ",\n  ".join(rows) + "\n};\n"
           "static const unsigned int %s_len = %d;\n" % (name, len(data)))
    (root / dst).write_text(out)
    print("%s: %d bytes" % (dst, len(data)))

emit("web/index.html", "src/index_html.h", "ng_index_html")
emit("netguard.conf", "src/default_conf.h", "ng_default_conf")
